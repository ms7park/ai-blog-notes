def run_tistory_batch(target_date=None, force=False):
    """티스토리 일별 배치 메인 실행"""
    lock_file_path = "/tmp/daily_tistory_batch.lock"
    try:
        lock_file = open(lock_file_path, "w")
        fcntl.flock(lock_file, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except (BlockingIOError, OSError):
        log("ℹ️ 이미 다른 프로세스에서 티스토리 배치가 실행 중입니다.")
        return

    now = datetime.now()
    today_date = datetime.strptime(target_date, "%Y-%m-%d") if target_date else now
    today_str = today_date.strftime("%Y-%m-%d")
    weekday_str = WEEKDAYS_KR[today_date.weekday()]

    log(f"🚀 [티스토리 배치 시작] Google Trends 상승 검색어 기반 티스토리 글 생성 (기준일: {today_str} {weekday_str}요일, force={force})")

    # 기존 작성된 모든 티스토리 글의 제목·본문요약·키워드 서명 수집 (중복 작성 원천 차단)
    existing_sigs = get_existing_tistory_signatures(exclude_date=today_str if force else None)

    evaluated_trends = fetch_google_trends_for_tistory(existing_sigs=existing_sigs)
    selected = [
        t for t in evaluated_trends
        if t["eval"]["is_selected"]
        and not is_duplicate_tistory_candidate(
            t["eval"]["final_title"],
            t["eval"].get("custom_core_summary", ""),
            t["keyword"],
            existing_sigs
        )
    ]

    # 만약 실시간 트렌드 10개 중 중복을 제외한 유효 주제가 없을 경우 상록수 미작성 주제 풀(TISTORY_EVERGREEN_POOL)에서 순차 선택
    if not selected:
        for pool_item in TISTORY_EVERGREEN_POOL:
            if not is_duplicate_tistory_candidate(pool_item["final_title"], pool_item["core_summary"], pool_item["keyword"], existing_sigs):
                fallback_item = {
                    "rank": 1,
                    "keyword": pool_item["keyword"],
                    "traffic": "상록수 추천",
                    "news_title": pool_item["search_question"],
                    "news_url": pool_item["official_refs"][0][1] if pool_item["official_refs"] else "",
                    "eval": {
                        "is_selected": True,
                        "cat_key": pool_item["cat_key"],
                        "cat_name": TISTORY_CATEGORIES[pool_item["cat_key"]]["name"],
                        "cat_ratio": TISTORY_CATEGORIES[pool_item["cat_key"]]["ratio"],
                        "matched_keyword": pool_item["keyword"],
                        "scores": pool_item["scores"].copy(),
                        "total_score": pool_item["total_score"],
                        "rec_level": "높음 (추천)",
                        "search_question": pool_item["search_question"],
                        "title_candidates": pool_item["title_candidates"],
                        "final_title": pool_item["final_title"],
                        "official_refs": pool_item["official_refs"],
                        "custom_core_summary": pool_item["core_summary"],
                        "custom_body_sections": pool_item["body_sections"]
                    }
                }
                selected = [fallback_item]
                break

    # 점수순 정렬 (가장 높은 평가 점수를 받은 주제를 #1편 메인으로 발행)
    selected_sorted = sorted(selected, key=lambda x: x["eval"]["total_score"], reverse=True)

    created_count = 0
    for t_item in selected_sorted[:2]:
        next_idx = created_count + 1
        post_id = today_str if next_idx == 1 else f"{today_str}-{next_idx}"
        if create_tistory_post(post_id, today_str, weekday_str, t_item, post_num=next_idx, force=force, existing_sigs=existing_sigs):
            created_count += 1

    log(f"📝 오늘 작성된 티스토리 검색형 포스팅: 총 {created_count}편 (중복 제목·내용 제외 완료)")

    posts = scan_tistory_posts()
    update_tistory_index_html(today_str, evaluated_trends, posts)
    update_root_portal_with_tistory(today_str, posts)

    gen_script = os.path.join(BASE_DIR, "tools", "generate_html.py")
    if os.path.exists(gen_script):
        os.system(f"{sys.executable} {gen_script} > /dev/null 2>&1")
        log("✅ 전체 가이드 뷰어(docs/index.html) 동기화 완료")

    log(f"🎉 [티스토리 배치 완료] {today_str} 티스토리 블로그 작업이 완료되었습니다.\n")

if __name__ == "__main__":
    force_mode = "--force" in sys.argv
    date_args = [a for a in sys.argv[1:] if not a.startswith("--")]
    t_date = date_args[0] if date_args else None
    run_tistory_batch(t_date, force=force_mode)
