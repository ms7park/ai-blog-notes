def normalize_text_for_dedup(text):
    """중복 비교를 위해 공백·특수문자를 제거한 소문자 정규화 문자열 반환"""
    if not text:
        return ""
    return re.sub(r"[^a-z0-9가-힣]", "", text.lower())

def get_existing_tistory_signatures(exclude_date=None):
    """
    기존 작성된 모든 티스토리 포스트(.md, .html)를 스캔하여
    중복 작성 방지를 위한 제목(titles), 핵심요약(summaries), 키워드(keywords) 집합을 반환합니다.
    - exclude_date: 특정 날짜(예: force 재생성 대상 날짜)의 기존 파일은 제외할 때 사용
    """
    all_files = glob.glob(os.path.join(POSTS_DIR, "*", "*.md")) + glob.glob(os.path.join(POSTS_DIR, "*.md"))
    titles = set()
    norm_titles = set()
    norm_summaries = set()
    keywords = set()

    for fpath in set(all_files):
        fname = os.path.basename(fpath).replace(".md", "")
        parts = fname.split("-")
        date_only = "-".join(parts[:3])
        if exclude_date and date_only == exclude_date:
            continue

        try:
            with open(fpath, "r", encoding="utf-8") as f:
                content = f.read()

            m_title = re.search(r"^#\s+(.+)$", content, re.M)
            if m_title:
                t_str = m_title.group(1).strip()
                titles.add(t_str)
                norm_titles.add(normalize_text_for_dedup(t_str))

            m_sum = re.search(r">\s*\*\*📌 핵심 요약\*\*:\s*(.+)$", content, re.M)
            if m_sum:
                s_str = m_sum.group(1).strip()
                norm_summaries.add(normalize_text_for_dedup(s_str)[:80])

            html_path = fpath[:-3] + ".html"
            if os.path.exists(html_path):
                with open(html_path, "r", encoding="utf-8") as hf:
                    h_content = hf.read()
                m_kw = re.search(r'Google Trends 상승 검색어:\s*\[([^\]]+)\]', h_content)
                if m_kw:
                    keywords.add(normalize_text_for_dedup(m_kw.group(1)))
        except Exception:
            pass

    return {
        "titles": titles,
        "norm_titles": norm_titles,
        "norm_summaries": norm_summaries,
        "keywords": keywords
    }

def is_duplicate_tistory_candidate(title, core_summary, keyword, existing_sigs):
    """후보 포스트의 제목 또는 본문 핵심 요약이 이미 작성된 글과 중복되는지 검사"""
    if not existing_sigs:
        return False
    nt = normalize_text_for_dedup(title)
    ns = normalize_text_for_dedup(core_summary)[:80] if core_summary else ""
    nk = normalize_text_for_dedup(keyword)

    if title in existing_sigs["titles"] or (nt and nt in existing_sigs["norm_titles"]):
        return True
    if ns and ns in existing_sigs["norm_summaries"]:
        return True
    if nk and nk in existing_sigs["keywords"]:
        return True
    return False

def match_keyword_safely(ck, target_text):
    """영문 단축 키워드(mac, ios, irp, isa, ai 등)가 다른 영단어 내부에 오매칭되는 것을 방지"""
    ck_low = ck.lower().strip()
    if re.match(r'^[a-z0-9\s]+$', ck_low):
        return bool(re.search(r'(?<![a-z0-9])' + re.escape(ck_low) + r'(?![a-z0-9])', target_text))
    return ck_low in target_text

