def create_tistory_post(post_id, date_str, weekday_str, trend_item, post_num=1, force=False, existing_sigs=None):
    """개별 티스토리 포스팅(.md 및 .html) 생성 (중복 제목·내용 자동 차단 포함)"""
    ym = date_str[:7].replace("-", "")
    post_dir = os.path.join(POSTS_DIR, ym)
    os.makedirs(post_dir, exist_ok=True)
    md_path = os.path.join(post_dir, f"{post_id}.md")
    html_path = os.path.join(post_dir, f"{post_id}.html")

    if not force and os.path.exists(md_path) and os.path.exists(html_path):
        log(f"ℹ️ tistory/posts/{ym}/{post_id} 파일이 이미 존재하여 보존합니다.")
        return False

    md_content = build_tistory_post_markdown(post_id, date_str, weekday_str, trend_item)
    m_title = re.search(r"^#\s+(.+)$", md_content, re.M)
    actual_title = m_title.group(1).strip() if m_title else trend_item["eval"]["final_title"]
    m_sum = re.search(r">\s*\*\*📌 핵심 요약\*\*:\s*(.+)$", md_content, re.M)
    actual_sum = m_sum.group(1).strip() if m_sum else ""

    if existing_sigs and is_duplicate_tistory_candidate(actual_title, actual_sum, trend_item["keyword"], existing_sigs):
        log(f"⏭️ [중복 작성 제외] 이미 동일한 제목 또는 내용의 글이 존재하여 건너뜁니다: {actual_title}")
        return False

    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md_content)
    log(f"✅ blog/tistory/posts/{ym}/{post_id}.md 생성 완료 (#{post_num}편: [{trend_item['keyword']}])")

    html_content = build_tistory_post_html(post_id, date_str, weekday_str, trend_item, md_content)
