def scan_tistory_posts():
    """blog/tistory/posts/ 하위 모든 마크다운 포스트 스캔"""
    all_files = glob.glob(os.path.join(POSTS_DIR, "*", "*.md")) + glob.glob(os.path.join(POSTS_DIR, "*.md"))

    def get_sort_key(f):
        base = os.path.basename(f).replace(".md", "")
        parts = base.split("-")
        d_str = "-".join(parts[:3])
        idx = int(parts[3]) if len(parts) > 3 else 1
        return (d_str, -idx)

    md_files = sorted(list(set(all_files)), key=get_sort_key, reverse=True)
    posts = []

    for fpath in md_files:
        fname = os.path.basename(fpath)
        post_id = fname.replace(".md", "")
        parts = post_id.split("-")
        date_only = "-".join(parts[:3])
        post_num = int(parts[3]) if len(parts) > 3 else 1

        rel_md = os.path.relpath(fpath, TISTORY_BLOG_DIR)
        rel_html = rel_md[:-3] + ".html"

        try:
            with open(fpath, "r", encoding="utf-8") as f:
                content = f.read()

            html_path = fpath[:-3] + ".html"
            html_content_str = ""
            if os.path.exists(html_path):
                with open(html_path, "r", encoding="utf-8") as hf:
                    html_content_str = hf.read()

            m_title = re.search(r"^#\s+(.+)$", content, re.M)
            title = m_title.group(1).strip() if m_title else post_id

            m_cat = re.search(r">\s*\*\*카테고리\*\*:\s*(.+)$", content, re.M) or re.search(r'<span class="badge">📂 카테고리:\s*([^<]+)</span>', html_content_str)
            if m_cat:
                category = m_cat.group(1).strip()
            elif "연금" in title or "건강보험" in title:
                category = "은퇴·연금·생활비"
            elif "AI" in title or "ChatGPT" in title or "팩트체크" in title:
                category = "AI·IT 활용법"
            else:
                category = "제품 비교·사용법"

            m_kw = re.search(r">\s*\*\*Google Trends 상승 검색어\*\*:\s*`?([^`\n]+)`?", content, re.M) or re.search(r'<span class="badge">📈 Google Trends 상승 검색어:\s*\[([^\]]+)\]</span>', html_content_str)
            trend_kw = m_kw.group(1).strip() if m_kw else ""

            m_score = re.search(r">\s*\*\*주제 평가 점수\*\*:\s*\*\*([0-9]+/100점)\*\*", content, re.M) or re.search(r'<span class="badge badge-score">🎯 주제 평가 점수:\s*([0-9]+/100점)</span>', html_content_str)
            if m_score:
                score_str = m_score.group(1).strip()
            elif "AI" in title or "ChatGPT" in title:
                score_str = "96/100점"
            elif "연금" in title:
                score_str = "88/100점"
            else:
                score_str = "80/100점"

            m_summary = re.search(r">\s*\*\*📌 핵심 요약\*\*:\s*(.+)$", content, re.M)
            desc = m_summary.group(1).strip().replace("**", "") if m_summary else ""
            if len(desc) > 150:
                desc = desc[:150] + "..."

            char_count = len(content.replace(" ", "").replace("\n", ""))

            posts.append({
                "post_id": post_id,
                "date_only": date_only,
                "post_num": post_num,
                "category": category,
                "trend_kw": trend_kw,
                "score_str": score_str,
                "title": title,
                "desc": desc,
                "char_count": char_count,
                "rel_md": rel_md,
                "rel_html": rel_html
            })
        except Exception as e:
            log(f"⚠️ 티스토리 포스트 파싱 오류 {fname}: {e}")

    return posts

